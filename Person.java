public class Person {
    private int speed;
    private String name;
    private double smartness;

    public void setspeed(int speed){
        this.speed = speed;
    }
    public void setname(String name){
        this.name = name;
    }
    public void setsmart(double smartness){
        this.smartness = smartness;
    }
    public String getname(){
        return name;
    }
    public int getspeed(){
        return speed;
    }
    public double getsmartness(){
        return smartness;
    }
    


}
